// Static security rules: one regular expression per line, applied to the original
// source (so secrets inside strings are visible) but never to matches that start
// inside a comment. Every pattern is linear (no nested quantifiers) and lines are
// capped before matching, so a hostile file cannot stall the editor.

export type Severity = 'low' | 'medium' | 'high' | 'critical';
export type Confidence = 'low' | 'medium' | 'high';

export interface SecurityRule {
  id: string;
  title: string;
  cwe: string;
  severity: Severity;
  languages: readonly string[] | '*';
  pattern: RegExp;
  /** The rule does not fire when this also matches the line. */
  unless?: RegExp;
  /** The rule fires only when this also matches the line. */
  requires?: RegExp;
  /** Dangerous sink: confidence follows the taint (user input > parameter > constant). */
  sink?: boolean;
  /** Fire only when tainted data reaches the line (for very common APIs). */
  requiresTaint?: boolean;
  /** The match may start inside a string literal (secrets, headers, config strings). */
  inStrings?: boolean;
  /** Specific format (e.g. an AWS key): high confidence on its own. */
  precise?: boolean;
  message: string;
  recommendation: string;
}

